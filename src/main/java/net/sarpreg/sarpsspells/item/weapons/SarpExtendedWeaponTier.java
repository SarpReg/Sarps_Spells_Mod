public class SarpExtendedWeaponTier implements Tier, IronsWeaponTier {

    public static ExtendedWeaponTier SANGUINE_TRIDENT = new ExtendedWeaponTier(9051, 9, -2.9f, 9, /*BlockTags.INCORRECT_FOR_DIAMOND_TOOL,*/ () -> Ingredient.of(Items.DIAMOND), new AttributeContainer(AttributeRegistry.CAST_TIME_REDUCTION, .15, AttributeModifier.Operation.MULTIPLY_BASE), new AttributeContainer(AttributeRegistry.BLOOD_SPELL_POWER, .1, AttributeModifier.Operation.MULTIPLY_BASE));

    int uses;
    float damage;
    float speed;
    int enchantmentValue;
    TagKey<Block> incorrectBlocksForDrops;
    Supplier<Ingredient> repairIngredient;
    AttributeContainer[] attributes;

    public SarpExtendedWeaponTier(int uses, float damage, float speed, int enchantmentValue, /*TagKey<Block> incorrectBlocksForDrops,*/ Supplier<Ingredient> repairIngredient, AttributeContainer... attributes) {
        this.uses = uses;
        this.damage = damage;
        this.speed = speed;
        this.enchantmentValue = enchantmentValue;
//        this.incorrectBlocksForDrops = incorrectBlocksForDrops;
        this.repairIngredient = repairIngredient;
        this.attributes = attributes;
    }

    @Override
    public int getUses() {
        return uses;
    }

    @Override
    public float getSpeed() {
        return speed;
    }

    @Override
    public float getAttackDamageBonus() {
        return damage;
    }

    @Override
    public int getLevel() {
        return 0;
    }

    @Override
    public int getEnchantmentValue() {
        return enchantmentValue;
    }

    @Override
    public Ingredient getRepairIngredient() {
        return repairIngredient.get();
    }

    @Override
    public AttributeContainer[] getAdditionalAttributes() {
        return this.attributes;
    }
}
